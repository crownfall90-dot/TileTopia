// One source of truth for the tile art: assets/tiles3d/tiles.json, built from TYPES in src/engine/tiles.js
// (rare x* cards included), so the 3D models and the 2D sprites always describe the cards the engine deals.
//   node scripts/gen-tile-defs.mjs          → writes the file
//   node scripts/gen-tile-defs.mjs --check  → fails if the file is out of date (CI / before rendering)
// The engine is not touched: this only reads TYPES.
import fs from 'node:fs';
import path from 'node:path';
import {TYPES} from '../src/engine/tiles.js';

const SIDES = ['N', 'E', 'S', 'W'];
const KIND = {c: 'city', r: 'road', w: 'river', f: 'field', b: 'bridge_half', x: 'cliff'};
const at = (e, k) => [...e].map((x, i) => x === k ? i : -1).filter(i => i >= 0);

/** Roads as drawn by src/render/art.js: two road edges make one road through the middle, any other number meet at a junction. */
function roads(e) {
  const r = at(e, 'r');
  if (r.length === 2) return [{from: r[0], to: r[1]}];
  return r.map(d => ({from: d, to: null}));
}

function rivers(e, t) {
  const w = at(e, 'w');
  if (t.lake) return [];
  if (w.length === 2) return [{from: w[0], to: w[1]}];
  return w.map(d => ({from: d, to: null}));
}

/** A road needs a bridge where it crosses a river: their edges alternate around the tile (wBr), not when they only share it (wRC). */
function crosses(rs, ws) {
  const between = (a, b, x) => { for (let i = (a + 1) % 4; i !== b; i = (i + 1) % 4) if (i === x) return true; return false; };
  return rs.some(r => r.to != null && ws.some(w => w.to != null && between(r.from, r.to, w.from) !== between(r.from, r.to, w.to)));
}

export function describe(id, t) {
  const e = t.e, city = at(e, 'c');
  const features = [];
  if (city.length) features.push('city');
  if (t.fort) features.push('fort');
  if (t.bridge) features.push('big_bridge');
  if (crosses(roads(e), rivers(e, t))) features.push('bridge');
  if (t.lake) features.push('lake');
  if (t.end) features.push(t.end);          // boulders | mine | cliff
  if (t.rocks) features.push('boulders');
  if (e.includes('x')) features.push('cliff');
  return {
    id,
    name: t.name,
    edges: e,
    sides: Object.fromEntries(SIDES.map((s, i) => [s, KIND[e[i]]])),
    count: t.n,
    rare: !!t.rare,
    city: city.length ? {edges: city} : null,
    roads: roads(e),
    rivers: rivers(e, t),
    lake: t.lake ? {edges: at(e, 'w')} : null,
    roadEnd: t.end || null,
    features: [...new Set(features)],
    sprite: `tile_${id}.png`,
    model: `classic/${id}.glb`,
  };
}

const out = path.resolve('assets/tiles3d/tiles.json');
const data = {
  note: 'Generated by scripts/gen-tile-defs.mjs from src/engine/tiles.js. Do not edit by hand.',
  sides: 'edges N E S W: c city, r road, w river, f field, b big-bridge half, x cliff',
  tiles: Object.entries(TYPES).map(([id, t]) => describe(id, t)),
};
const text = JSON.stringify(data, null, 1) + '\n';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== text) { console.error('assets/tiles3d/tiles.json is out of date: run node scripts/gen-tile-defs.mjs'); process.exit(1); }
  console.log(`tiles.json up to date (${data.tiles.length} tiles)`);
} else {
  fs.mkdirSync(path.dirname(out), {recursive: true});
  fs.writeFileSync(out, text);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${data.tiles.length} tiles)`);
}
