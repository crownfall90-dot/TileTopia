// The Classic 2.0 cards for Blender: every card type with its sides and shapes (src/engine/hex.js shapes), so the
// renders put each road, river, town wall and monastery exactly where the game draws the owner colours.
//   node scripts/gen-hex-defs.mjs   → tools/blender_generators/hex_shapes.json
// Re-run after changing src/engine/hex.js, then tools/blender_generators/generate_hex_tiles.py.
import fs from 'node:fs';
import {TYPES, GEO, shapes, corner} from '../src/engine/hex.js';

const out = {
  note: 'Generated by scripts/gen-hex-defs.mjs from src/engine/hex.js. Unit: card height = 1, origin in the middle, x right, y down.',
  geo: GEO,
  corners: [0, 1, 2, 3, 4, 5].map(corner),
  types: Object.fromEntries(Object.entries(TYPES).map(([id, t]) => [id, {...t, shapes: shapes(id)}])),
};
fs.writeFileSync(new URL('../tools/blender_generators/hex_shapes.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log('hex_shapes.json:', Object.keys(TYPES).length, 'types');
