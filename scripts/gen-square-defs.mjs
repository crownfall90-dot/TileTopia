// The classic cards for Blender: every card type that gets a render, with its sides and shapes (src/engine/square.js),
// in the same format as scripts/gen-hex-defs.mjs, so tools/blender_generators/generate_hex_tiles.py renders them too:
//   node scripts/gen-square-defs.mjs   → tools/blender_generators/square_shapes.json
//   blender -b -P tools/blender_generators/generate_hex_tiles.py -- --shapes square_shapes.json --out build/square-render
import fs from 'node:fs';
import {TYPES} from '../src/engine/tiles.js';
import {GEO, V, corner, shapes, RENDERED} from '../src/engine/square.js';

const out = {
  note: 'Generated by scripts/gen-square-defs.mjs from src/engine/square.js. Unit: card side = 1, origin in the middle, x right, y down.',
  geo: GEO, dirs: V,
  corners: [0, 1, 2, 3].map(corner),
  types: Object.fromEntries([...RENDERED].map(id => [id, {...TYPES[id], shapes: shapes(id)}])),
};
fs.writeFileSync(new URL('../tools/blender_generators/square_shapes.json', import.meta.url), JSON.stringify(out, null, 1) + '\n');
console.log('square_shapes.json:', RENDERED.size, 'types');
